package dev.anchormc.core;

public enum Result {
    /** 반경 안까지 옴. */
    HIT,
    /** 시간 창이 끝나거나 멀어질 때까지 안 옴. */
    MISS,
    /**
     * 판정 창(MISS)이 끝난 뒤 처음 반응한 경우(1.2단계). 혼합·판정에는 쓰지 않고 "먼저 반응한 쪽" 검정에만 쓴다.
     * 창은 혼합 e-value가 반응률을 재는 단위일 뿐이고, 먼저 반응한 쪽 검정은 언제든 처음 나온 반응을 센다.
     */
    LATE_HIT,
    /** 노출 위험·접속 종료 등으로 판정 전에 거둠. 증거에서 제외한다. */
    VOID
}
